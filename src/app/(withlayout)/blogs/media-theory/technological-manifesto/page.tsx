import Link from "next/link";
import blogData from "@/data/media-theory-blogs.json";
import blogSeries from "@/data/blog-series.json";
import path from "path";
import { fileURLToPath } from "url";

// Define type
type BlogPostType = {
  title: string;
  id: string;
  date: string;
  tag: string;
  description: string
};

// Resolve file path
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Extract "media-theory" and id from the file path
const segments = __dirname.split(path.sep);
const tag = segments[segments.length - 2]; // "media-theory"
const id = segments[segments.length - 1]; // id

// Find the selected blog post
const blogDataArray: BlogPostType[] = blogData;
const selectedBlog = blogDataArray.find(
  (post) => post.tag === tag && post.id === id
);

if (!selectedBlog) {
  throw new Error("Blog not found");
}

// Find the blog series title
const selectedBlogSeries = blogSeries[(blogSeries.findIndex((item) => item.blogTag == tag))].blogName;

export default function Main() {
  return (
    <div>
          {/* metadata */}
          <h2>{selectedBlog?.title}</h2>
          <p className="text-date">{selectedBlog?.date}</p>
          <p className="mb-4 text-secondary">
            <b>Blog series: </b>
            <Link key={tag} href={`/blogs/${tag}`} className="hover:underline">
              {selectedBlogSeries}
            </Link>
          </p>
          <p>{selectedBlog?.description}</p>
          
          {/* blog content */}
          <div>
            <p>This week&apos;s readings are manifestos in the context of modern technology advancement. They all make bold claims about the future of the world and look forward to the future with technology, albeit from different standpoints. Upon reading these manifestos, I now hold a different perspective on a manifesto from what I previously thought of when reading the Unabomber Manifesto: it is not the logic of a manifesto that matters the most (because the nature of the manifesto is inflammatory), but the series of guidelines it promotes.</p>
            <p>Modern technology creates many opportunities as well as problems. While none of these manifestos advocate for the past, they express different levels of optimism toward the future. For example, The Futurist Manifesto holds a totally negative attitude towards the past and shows firm belief in the future. Museums as a typical example of the past are commented on in this manifesto as lifeless and worthless. I disagree with this point because I think humans shouldn&apos;t and wouldn&apos;t be able to avoid learning from the past; those who forget history will likely fall for the same mistakes. This might explain why the manifesto surprisingly advocates for many ideas that have long been proven wrong by history, like glorifying war (not a popular and universally accepted idea after WWI) and contempt for women (this almost excludes half of the world&apos;s population from the futurists, which is destructive as a manifesto&apos;s dissemination requires a mass base).</p>
            <p>The Crypto Anarchist Manifesto, A Cypherpunk&apos;s Manifesto, A Declaration of the Independence of Cyberspace, and The Pluriverse Manifesto support the decentralization trend driven by computer technology. They support polycentrism and plurality, and therefore are strongly against any form of monopoly, from large organizations&apos; regulations on private information to “privilege or prejudice accorded by race, economic power, military force, or station of birth.” They see information technology advances as a chance to promote liberty and equality for all. Among the four manifestos, I resonate with the fourth point about Engagement and Attention addressed by The Pluriverse Manifesto. It acknowledges people&apos;s attention as a creative force, and it is a pity that this force is exploited merely for monetization in the IT industry. This point reminds me of an Attention Lab event I attended last weekend, during which I learned to consciously elevate my attention to do meaningful things other than browsing digital media. When focusing on face-to-face interactions, I got to meet people and learn from each other, which made me feel a sense of satisfaction and peace. On the contrary, putting aside the anxiety and emptiness social media platforms cause me, the money they make from my information and activities far exceeds the value they provide me, which is unfair.</p>
            <p>The Techno-Optimist Manifesto states that technology does more good than bad, and it glorifies the freedom brought by technology. However, I have several doubts as follows: 1) it refers to William Nordhaus&apos;s theory that 98% of economic value generated by technology flows back to society as social surplus, thus technology advancement is inherently philanthropic. However, what we see is that the social surplus somehow tends to benefit people with capital. As mentioned in the manifesto by the author itself, relying on love for others to contribute is unrealistic. Therefore, compared with free markets, I think proper regulations can do a better job of making social surplus benefit the wider population. 2) It states that “all the machines work for us”. However, I think a clearer definition of “us” is necessary. Do people addicted to video games or with severe body/appearance anxiety due to social platform content also belong to the “us”?</p>
            <p>I find myself resonating with The New Technologist Manifesto maybe because I consider myself a technologist. Some people blame technologists for creating and implementing technology without careful thinking, but that is not true. Technologists know technology the best and are concerned about its usage and impacts. In the age of modern technology, the views of technical experts deserve to be taken seriously.</p>
            <p>Together, the manifestos I read this week show human society&apos;s chaos and dynamics in the face of the future with technology. Although not necessarily coming to a common agreement, I believe it is better to have more discussions worldwide with help from modern technology like the Internet; the more debates, the clearer the truth.</p>
          </div>
        </div>
  );
}
